package Facade;

public class DVD {
    public void on() { System.out.println("DVD ligado."); }
    public void off() { System.out.println("DVD desligado."); }
    public void play() { System.out.println("DVD a reproduzir."); }
    public void pause() { System.out.println("DVD em pausa."); }
    public void load() { System.out.println("DVD carregado."); }
    public void eject() { System.out.println("DVD ejectado."); }
    public void stop() { System.out.println("DVD parado."); }
}
